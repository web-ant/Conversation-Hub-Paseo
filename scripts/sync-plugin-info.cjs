const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'paseo-plugin.json'), 'utf8'));
function overview(file) {
  const blocks = fs.readFileSync(path.join(root, file), 'utf8').trim().split(/\n\s*\n/);
  return blocks.slice(1).map(block => block.startsWith('## ')
    ? { kind: 'heading', text: block.slice(3).trim() }
    : { kind: 'paragraph', text: block.replace(/\n/g, ' ') });
}
const content = {
  name: manifest.name,
  ru: overview('OVERVIEW.ru.md'),
  en: overview('OVERVIEW.md'),
};
const banner = '// Generated by npm run sync-info from the manifest, icon, and English/Russian overviews.\n';
fs.writeFileSync(path.join(root, 'client/plugin-info-content.ts'), banner + 'export const pluginInfo = ' + JSON.stringify(content, null, 2) + ' as const;\n');
const icon = 'data:image/png;base64,' + fs.readFileSync(path.join(root, manifest.icon)).toString('base64');
fs.writeFileSync(path.join(root, 'client/plugin-icon-data.ts'), banner + 'export const pluginIconUri = ' + JSON.stringify(icon) + ';\n');
console.log('Synced the embedded icon and English/Russian descriptions for the installed settings screen.');
